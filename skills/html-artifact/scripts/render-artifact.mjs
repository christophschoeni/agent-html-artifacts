#!/usr/bin/env node
import { readFile, writeFile } from "node:fs/promises";
import { basename } from "node:path";

const [inputPath, outputPath] = process.argv.slice(2);

if (!inputPath || !outputPath) {
  console.error("Usage: render-artifact <input.json> <output.html>");
  process.exit(1);
}

const data = JSON.parse(await readFile(inputPath, "utf8"));
const now = new Date().toISOString().slice(0, 10);

function escapeHtml(value = "") {
  return String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;");
}

function list(items = []) {
  return `<ul>${items.map((item) => `<li>${escapeHtml(item)}</li>`).join("")}</ul>`;
}

function cards(items = []) {
  return items.map((item) => `
    <article class="card">
      <h3>${escapeHtml(item.title)}</h3>
      <p>${escapeHtml(item.body || item.summary || "")}</p>
      ${item.items ? list(item.items) : ""}
    </article>
  `).join("");
}

const html = `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>${escapeHtml(data.title || "HTML Artifact")}</title>
  <style>
    :root { --bg:#f7f6f2; --ink:#1f2933; --muted:#65717c; --line:#d9d4ca; --panel:#fff; --accent:#0f766e; }
    * { box-sizing:border-box; }
    body { margin:0; background:var(--bg); color:var(--ink); font-family:ui-sans-serif,system-ui,-apple-system,BlinkMacSystemFont,"Segoe UI",sans-serif; line-height:1.5; }
    header, main, footer { max-width:1100px; margin:0 auto; padding:28px 22px; }
    header { border-bottom:1px solid var(--line); }
    h1 { margin:0 0 10px; font-size:42px; letter-spacing:0; }
    h2 { margin:28px 0 12px; font-size:24px; }
    .meta, .muted { color:var(--muted); }
    .grid { display:grid; grid-template-columns:repeat(auto-fit,minmax(250px,1fr)); gap:14px; }
    .card { background:var(--panel); border:1px solid var(--line); border-radius:8px; padding:16px; }
    .summary { font-size:18px; max-width:760px; }
    button { border:1px solid var(--accent); background:var(--accent); color:white; border-radius:6px; padding:8px 11px; font-weight:700; cursor:pointer; }
    pre { white-space:pre-wrap; background:#14213d; color:#f8fafc; padding:14px; border-radius:8px; overflow:auto; }
    @media print { button { display:none; } body { background:white; } }
  </style>
</head>
<body>
  <header>
    <div class="meta">${escapeHtml(data.type || "Artifact")} · ${now} · source: ${escapeHtml(basename(inputPath))}</div>
    <h1>${escapeHtml(data.title || "HTML Artifact")}</h1>
    <p class="summary">${escapeHtml(data.summary || "")}</p>
    <button id="copy-source">Copy source JSON</button>
  </header>
  <main>
    ${(data.sections || []).map((section) => `
      <section>
        <h2>${escapeHtml(section.title)}</h2>
        ${section.body ? `<p>${escapeHtml(section.body)}</p>` : ""}
        ${section.items ? list(section.items) : ""}
        ${section.cards ? `<div class="grid">${cards(section.cards)}</div>` : ""}
      </section>
    `).join("")}
    <section>
      <h2>Source</h2>
      <pre id="source-json">${escapeHtml(JSON.stringify(data, null, 2))}</pre>
    </section>
  </main>
  <footer class="meta">Generated by html-artifact.</footer>
  <script>
    document.getElementById("copy-source").addEventListener("click", async () => {
      await navigator.clipboard.writeText(document.getElementById("source-json").textContent);
    });
  </script>
</body>
</html>`;

await writeFile(outputPath, html);
console.log(`Wrote ${outputPath}`);
